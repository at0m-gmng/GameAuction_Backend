namespace GameBackend.SharedKernel.Domain;

/// <summary>
/// Редкость предмета. Влияет на ценность и используется фильтром "Rare+".
/// Хранится как smallint: значений мало, int избыточен.
/// 
/// Шаг между уровнями = 100, чтобы оставался запас для вставки промежуточных
/// уровней без сдвига существующих (иначе сломается семантика старых данных в БД).
/// Правило: НИКОГДА не менять уже присвоенные значения, только добавлять новые.
/// </summary>
public enum ItemRarity : short
{
    /// <summary>Обычный предмет.</summary>
    Common = 100,

    /// <summary>Редкий предмет.</summary>
    Rare = 200,

    /// <summary>Эпический предмет.</summary>
    Epic = 300,

    /// <summary>Легендарный предмет.</summary>
    Legendary = 400
}