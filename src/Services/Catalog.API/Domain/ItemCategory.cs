/// Правило: НИКОГДА не менять уже присвоенные значения, только добавлять новые.
/// </summary>
public enum ItemCategory : short
{
    /// <summary>Оружие.</summary>
    Weapons = 100,

    /// <summary>Броня.</summary>
    Armor = 200,

    /// <summary>Техника и гаджеты.</summary>
    Tech = 300
}